"""Generate the BigQuery patent-count SQL from config/domains.yaml.

Phase 3.5 workaround (2026-10-28): the USPTO ODP API key requires ID.me
identity verification (passport-gated for international users — unavailable),
and the PatentsView bulk TSVs (~1 GB zipped, ~10 GB unpacked) exceed local
disk. The Google Patents Public Data mirror on BigQuery
(`patents-public-data.patents.publications`, CC BY 4.0, updated quarterly)
carries the same bibliographic fields this pipeline needs: publication
number, US grant date, and CPC codes.

The workaround: compute the counts IN BigQuery (sandbox — no credit card,
1 TB scanned/month free) and download only the aggregated result
(~500 rows, a few KB). The query is generated from the same
`patent_cpc_codes` in config/domains.yaml that would have driven the ODP
fetch, so the CPC↔domain concordance stays single-sourced.

Usage:
    .venv/bin/python scripts/gen_patent_query.py            # → sql/patent_counts.sql
    .venv/bin/python scripts/gen_patent_query.py --stdout   # print only

Then (human step, ~10 min):
  1. Open https://console.cloud.google.com/bigquery (sandbox — sign in with
     any Google account; no billing account needed).
  2. Paste the generated SQL, run it (check "query will process ~X GB" —
     expect well under the 1 TB monthly free tier).
  3. Download results as CSV → save to data/patents/patent_counts.csv.
  4. `make patents` → builds data/patents/patent_series.json, joins the
     panel, refreshes snapshots.

Concordance semantics (documented, deterministic):
  * A configured code `G06N3/00` (subgroup 00) is treated as a parent group:
    it matches every patent leaf `G06N3/xx`. A configured `G06N3/08` matches
    only that exact leaf.
  * A patent matching several domains counts ONCE PER MATCHED DOMAIN
    (multi-membership). The known overlaps are parent/child pairs:
    G06N10/70 (QEC) ⊂ G06N10/00 (quantum_computing) — consistent with the
    existing twin-series caveat; G06N3/08+G06N3/04 (generative_ai) and
    G06N3/092 (ai_agents) ⊂ G06N3/00 (artificial_intelligence).
  * Counts are US granted patents (kind B*) by GRANT year, 2000–2025.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
DOMAINS = REPO / "config" / "domains.yaml"
OUT = REPO / "sql" / "patent_counts.sql"

YEAR_MIN, YEAR_MAX = 2000, 2025


def load_rows() -> list[tuple[str, str, str]]:
    raw = yaml.safe_load(DOMAINS.read_text(encoding="utf-8"))
    rows: list[tuple[str, str, str]] = []
    for d in raw["domains"]:
        for code in d.get("patent_cpc_codes", []):
            group, subgroup = code.split("/")
            rows.append((group, subgroup, d["domain_slug"]))
    if not rows:
        raise SystemExit("no patent_cpc_codes found in config/domains.yaml")
    return rows


def build_sql(rows: list[tuple[str, str, str]]) -> str:
    values = ",\n".join(
        f"  ('{g}', '{s}', '{slug}')" for g, s, slug in rows
    )
    return f"""-- Generated by scripts/gen_patent_query.py from config/domains.yaml — do not edit by hand.
-- Regenerate: .venv/bin/python scripts/gen_patent_query.py
--
-- US granted patents per technology domain per grant year, 2000–{YEAR_MAX}.
-- Source: patents-public-data.patents.publications (Google Patents Public
-- Data, CC BY 4.0). Run in the BigQuery sandbox (no billing account needed);
-- download the result as CSV to data/patents/patent_counts.csv.
--
-- Concordance: a configured subgroup '00' code matches every leaf in its
-- group; a specific subgroup matches exactly. A patent matching several
-- domains counts once per matched domain (multi-membership; the known
-- overlaps are parent/child pairs — see scripts/gen_patent_query.py).

WITH cfg (cpc_group, cpc_subgroup, domain) AS (
  VALUES
{values}
),
us_grants AS (
  SELECT
    p.publication_number,
    DIV(p.grant_date, 10000) AS grant_year,
    c.code AS cpc_code
  FROM `patents-public-data.patents.publications` AS p,
       UNNEST(p.cpc) AS c
  WHERE p.country_code = 'US'
    AND p.grant_date BETWEEN {YEAR_MIN}0101 AND {YEAR_MAX}1231
    AND p.kind_code LIKE 'B%'
),
matched AS (
  SELECT
    g.publication_number,
    g.grant_year,
    cfg.domain
  FROM us_grants AS g
  JOIN cfg
    ON cfg.cpc_group = SPLIT(g.cpc_code, '/')[OFFSET(0)]
   AND (cfg.cpc_subgroup = '00'
        OR cfg.cpc_subgroup = SPLIT(g.cpc_code, '/')[SAFE_OFFSET(1)])
)
SELECT
  domain,
  grant_year AS year,
  COUNT(DISTINCT publication_number) AS patents
FROM matched
GROUP BY domain, grant_year
ORDER BY domain, grant_year;
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stdout", action="store_true", help="print SQL instead of writing sql/patent_counts.sql")
    args = ap.parse_args()
    sql = build_sql(load_rows())
    if args.stdout:
        sys.stdout.write(sql)
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(sql, encoding="utf-8")
    print(f"patent query → {OUT} ({len(load_rows())} CPC rules, 20 domains)")
    print("next: paste into BigQuery sandbox → download CSV → data/patents/patent_counts.csv")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
